"""Write each subject's declaration: every inventory member answered
"supported". Every subject is measured against the whole inventory, and the
declaration reveals nothing about results: those stay in the private results
repository.

    oracle subjects [OUT_DIR [SCENARIO_DIR]]
        writes temper/subjects/*.yml (default /temper-subjects) and
        temper/scenarios/compat.yml (default /temper-scenarios)
"""
import json
import sys
from pathlib import Path

from compat.inventory import LATTICES, load

SUBJECTS = {
    "postgres.reference": {
        "feature": "reference.postgres17",
        "doc": "PostgreSQL 17.12 (postgres:17.12), compared with itself: three servers, one per side.",
    },
    "pg_duckdb.release": {
        "feature": "subject.pg_duckdb",
        "doc": "pg_duckdb 1.2.1 on PostgreSQL 17.12, three servers. Side b sets duckdb.force_execution = true; sides a and a2 run without it.",
    },
}


def render(subject: str, inv: dict) -> str:
    meta = SUBJECTS[subject]
    lines = [
        "# GENERATED by compat/subjects.py. Do not edit.",
        f"# {meta['doc']}",
        f"id: {subject}",
        "kind: database",
        f"feature: {meta['feature']}",
        "answers:",
    ]
    for lattice in LATTICES:
        lines.append(f"  {lattice}:")
        for m in inv[lattice]:
            lines.append(f"    {json.dumps(m.key)}: supported")
    return "\n".join(lines) + "\n"


# The lattices the scenario decides. sql.standard, server.setting,
# server.errcode and catalog.table are not decided (see the scenario's header).
DECIDED = ("sql.command", "sql.syntax", "sql.function", "sql.operator", "sql.type")

SCENARIO_HEAD = """# GENERATED by compat/subjects.py. Do not edit.
# The whole corpus on PostgreSQL and on each subject.
#
#   temper run --out <results>/postgres --level compat -- \\
#     temper scenarios run --scenario compat.replay --subject pg_duckdb.release --build
#
# sql.standard, server.setting, server.errcode and catalog.table are not
# decided here: no statement maps to an SQL-standard feature id yet, and for
# pg_duckdb the settings, error codes and catalogs are PostgreSQL's own code.
# Their cells read missing, and REPORT.md says why.
- id: compat.replay
  runner: temper
  name: Every corpus statement gives PostgreSQL's answer on the subject
  description: >
    PostgreSQL's regression tests in schedule order, the examples in its
    docs and captured application traffic run on PostgreSQL (side a),
    PostgreSQL again (side a2, the negative control: a statement whose two
    PostgreSQL answers differ is dropped) and the subject (side b). Each
    statement matches, differs, is refused, is documented as different, or
    was handed back to PostgreSQL. A feature passes when a statement using it
    matched, and fails when a failing statement can be pinned on it alone.
  compose: compose.yml
  subjects:
    postgres.reference: {reference: 1, reference_a2: 1, reference_b: 1}
    pg_duckdb.release: {reference: 1, pg_duckdb_a: 1, pg_duckdb_a2: 1, pg_duckdb: 1}
"""


def scenario(inv: dict) -> str:
    lines = [SCENARIO_HEAD.rstrip("\n"), "  covers:", "    - compat.matches_postgres"]
    for lattice in DECIDED:
        for m in inv[lattice]:
            lines.append("    - " + json.dumps(f"{lattice}/{m.key}"))
    lines += [
        "  events:",
        "    - up: {$subject: true}",
        '    - run: [oracle, replay, "{subject}"]',
        "    - check:",
        "        results:",
        '          run: [oracle, check, "{subject}", compat]',
        "          decides: [compat.matches_postgres]",
    ]
    for lattice in DECIDED:
        lines += [
            "    - check:",
            "        results:",
            f'          run: [oracle, check, "{{subject}}", {lattice}]',
            f"          decides: [{lattice}/*]",
        ]
    return "\n".join(lines) + "\n"


def main(argv) -> int:
    out = Path(argv[0] if argv else "/temper-subjects")
    scen = Path(argv[1] if len(argv) > 1 else "/temper-scenarios")
    inv = load(Path("/lattices"))
    for subject in SUBJECTS:
        (out / f"{subject}.yml").write_text(render(subject, inv))
        print(f"wrote {subject}.yml")
    (scen / "compat.yml").write_text(scenario(inv))
    print("wrote compat.yml")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
