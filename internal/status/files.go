// Header opens every status file.
const Header = "# Generated by temper. Do not edit by hand."

// Files renders the set as status files, keyed by path relative to the
// status directory. One row per line, sorted, levels in the given order:
// git merges two branches that flip different rows without conflict.
func Files(s Set, levels []string) map[string][]byte {
	out := map[string][]byte{
		"features.yml": render(s.Features, "feature, sorted by id", levels),
	}
	for subject, rows := range s.Subjects {
		if len(rows) == 0 {
			continue
		}
		out[path.Join("subjects", subject+".yml")] = render(rows, "invariant or lattice member that applies to "+subject+", sorted by id", levels)
	}
	for lattice, rows := range s.Lattices {
		if len(rows) == 0 {
			continue
		}
		out[path.Join("lattices", lattice+".yml")] = render(rows, "member of lattice "+lattice+", sorted by key", levels)
	}
	return out
}

func render(rows map[string]Row, about string, levels []string) []byte {
	var b bytes.Buffer
	b.WriteString(Header + "\n")
	fmt.Fprintf(&b, "# One line per %s: the status at each level.\n", about)
	ids := make([]string, 0, len(rows))
	for id := range rows {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		var cells []string
		for _, l := range levels {
			if st, ok := rows[id][l]; ok {
				cells = append(cells, l+": "+string(st))
			}
		}
		fmt.Fprintf(&b, "%s: {%s}\n", key(id), strings.Join(cells, ", "))
	}
	return b.Bytes()
}

var bare = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_.<>-]*(/[A-Za-z_][A-Za-z0-9_.<>-]*)?$`)

var yamlWords = map[string]bool{"true": true, "false": true, "yes": true, "no": true, "on": true, "off": true, "null": true, "y": true, "n": true}

// key writes an id bare when YAML reads it back unchanged, quoted otherwise.
func key(id string) string {
	if bare.MatchString(id) && !yamlWords[strings.ToLower(id)] {
		return id
	}
	return strconv.Quote(id)
}

// Read is the inverse of Files over a written directory. A missing
// directory reads as an empty set.
func Read(dir string) (Set, error) {
	s := NewSet()
	read := func(rel string) (map[string]Row, error) {
		raw, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
		if err != nil {
			return nil, err
		}
		var rows map[string]map[string]string
		if err := yaml.Unmarshal(raw, &rows); err != nil {
			return nil, fmt.Errorf("%s: %w", rel, err)
		}
		out := map[string]Row{}
		for id, cells := range rows {
			out[id] = Row{}
			for l, st := range cells {
				out[id][l] = Status(st)
			}
		}
		return out, nil
	}
	for _, rel := range managed(dir) {
		rows, err := read(rel)
		if err != nil {
			return s, err
		}
		name := strings.TrimSuffix(path.Base(rel), ".yml")
		switch path.Dir(rel) {
		case ".":
			if rel == "features.yml" {
				s.Features = rows
			}
		case "subjects":
			s.Subjects[name] = rows
		case "lattices":
			s.Lattices[name] = rows
		}
	}
	return s, nil
}

// managed lists the .yml files the generator owns under dir: the top level,
// subjects/ and lattices/. A missing directory owns none.
func managed(dir string) []string {
	var out []string
	for _, sub := range []string{".", "subjects", "lattices"} {
		entries, err := os.ReadDir(filepath.Join(dir, sub))
		if err != nil {
			continue
		}
		for _, e := range entries {
			if !e.IsDir() && strings.HasSuffix(e.Name(), ".yml") {
				out = append(out, path.Join(sub, e.Name()))
			}
		}
	}
	sort.Strings(out)
	return out
}

// Write writes files under dir and removes every .yml file the generator
// owns that files no longer includes. Files it does not own are left alone.
func Write(dir string, files map[string][]byte) error {
	for rel, content := range files {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, content, 0o644); err != nil {
			return err
		}
	}
	for _, rel := range managed(dir) {
		if _, ok := files[rel]; !ok {
			if err := os.Remove(filepath.Join(dir, filepath.FromSlash(rel))); err != nil {
				return err
			}
		}
	}
	return nil
}

// Diff returns the paths Write would create, change or remove, sorted.
func Diff(dir string, files map[string][]byte) ([]string, error) {
	var out []string
	for rel, content := range files {
		raw, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			return nil, err
		}
		if err != nil || !bytes.Equal(raw, content) {
			out = append(out, rel)
		}
	}
	for _, rel := range managed(dir) {
		if _, ok := files[rel]; !ok {
			out = append(out, rel)
		}
	}
	sort.Strings(out)
	return out, nil
}
