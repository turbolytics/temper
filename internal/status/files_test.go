func TestStatus_WriteRemovesStale(t *testing.T) {
	temper.Covers(t, "cli.matrix")
	dir := t.TempDir()
	for _, name := range []string{"subjects/old.yml", "lattices/old.yml", "old.yml", "README.txt"} {
		path := filepath.Join(dir, name)
		os.MkdirAll(filepath.Dir(path), 0o755)
		os.WriteFile(path, []byte("x\n"), 0o644)
	}
	if err := Write(dir, Files(smallSet(), lv)); err != nil {
		t.Fatal(err)
	}
	for _, gone := range []string{"subjects/old.yml", "lattices/old.yml", "old.yml"} {
		if _, err := os.Stat(filepath.Join(dir, gone)); !os.IsNotExist(err) {
			t.Errorf("%s survived", gone)
		}
	}
	if _, err := os.Stat(filepath.Join(dir, "README.txt")); err != nil {
		t.Error("a file the generator does not own was removed")
	}
}

func TestStatus_Diff(t *testing.T) {
	temper.Covers(t, "cli.matrix_check")
	temper.Covers(t, "matrix.stale_output_detected", temper.Subject("cli"))
	dir := t.TempDir()
	files := Files(smallSet(), lv)
	if err := Write(dir, files); err != nil {
		t.Fatal(err)
	}
	if d, err := Diff(dir, files); err != nil || len(d) != 0 {
		t.Fatalf("Diff of identical = %v, %v", d, err)
	}

	changed := smallSet()
	changed.Put("feature", "cli.check", "", "", "unit", Covered)
	changed.Put("feature", "new.one", "", "", "unit", Covered)
	changed.Put("feature", "new.one", "", "", "integration", Covered)
	delete(changed.Lattices, "heuristics")
	changed.Put("invariant", "x", "", "sink.pg", "unit", Covered)
	changed.Put("invariant", "x", "", "sink.pg", "integration", Covered)

	d, err := Diff(dir, Files(changed, lv))
	want := []string{"features.yml", "lattices/heuristics.yml", "subjects/sink.pg.yml"}
	if err != nil || !reflect.DeepEqual(d, want) {
		t.Fatalf("Diff = %v, %v; want %v", d, err, want)
	}
}
