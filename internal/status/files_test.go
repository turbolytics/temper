package status

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/turbolytics/temper"
)

var lv = []string{"unit", "integration"}

func smallSet() Set {
	s := NewSet()
	s.Put("feature", "sink.kafka", "", "", "unit", Covered)
	s.Put("feature", "sink.kafka", "", "", "integration", NotRequired)
	s.Put("feature", "cli.check", "", "", "unit", Missing)
	s.Put("feature", "cli.check", "", "", "integration", Failing)
	s.Put("invariant", "sink.flush.keeps_batch", "", "sink.kafka", "unit", NotRequired)
	s.Put("invariant", "sink.flush.keeps_batch", "", "sink.kafka", "integration", Exempt)
	s.Put("lattice", "sink.types", "list<int64>", "sink.kafka", "unit", NotRequired)
	s.Put("lattice", "sink.types", "list<int64>", "sink.kafka", "integration", Unenforced)
	s.Put("lattice", "heuristics", "up.working", "", "unit", Covered)
	s.Put("lattice", "heuristics", "up.working", "", "integration", NotRequired)
	return s
}

func TestStatus_FileFormat(t *testing.T) {
	temper.Covers(t, "cli.matrix")
	files := Files(smallSet(), lv)
	want := map[string]string{
		"features.yml": `# Generated by temper. Do not edit by hand.
# One line per feature, sorted by id: the status at each level.
cli.check: {unit: missing, integration: failing}
sink.kafka: {unit: covered, integration: not_required}
`,
		"subjects/sink.kafka.yml": `# Generated by temper. Do not edit by hand.
# One line per invariant or lattice member that applies to sink.kafka, sorted by id: the status at each level.
sink.flush.keeps_batch: {unit: not_required, integration: exempt}
sink.types/list<int64>: {unit: not_required, integration: unenforced}
`,
		"lattices/heuristics.yml": `# Generated by temper. Do not edit by hand.
# One line per member of lattice heuristics, sorted by key: the status at each level.
up.working: {unit: covered, integration: not_required}
`,
	}
	if len(files) != len(want) {
		t.Fatalf("files = %v", keys(files))
	}
	for name, content := range want {
		if string(files[name]) != content {
			t.Errorf("%s =\n%s\nwant\n%s", name, files[name], content)
		}
	}
}

func keys(m map[string][]byte) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	return out
}

func TestStatus_EmptySetStillHasFeatures(t *testing.T) {
	temper.Covers(t, "cli.matrix")
	files := Files(NewSet(), lv)
	if len(files) != 1 || files["features.yml"] == nil {
		t.Fatalf("files = %v, want only features.yml", keys(files))
	}
}

func TestStatus_KeysRoundTrip(t *testing.T) {
	temper.Covers(t, "cli.matrix")
	s := NewSet()
	for _, k := range []string{"list<int64>", "a:b", "#x", "a,b", "true", "1", "<<", "{x}", `q"uote`} {
		s.Put("lattice", "l", k, "sub.a", "unit", Covered)
		s.Put("lattice", "l", k, "sub.a", "integration", NotRequired)
		s.Put("lattice", "h", k, "", "unit", Missing)
		s.Put("lattice", "h", k, "", "integration", NotRequired)
	}
	s.Put("feature", "2fa.login", "", "", "unit", Covered)
	s.Put("feature", "2fa.login", "", "", "integration", NotRequired)

	dir := t.TempDir()
	if err := Write(dir, Files(s, lv)); err != nil {
		t.Fatal(err)
	}
	got, err := Read(dir)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, s) {
		t.Fatalf("round trip changed the set:\n got %+v\nwant %+v", got, s)
	}
}

func TestStatus_Deterministic(t *testing.T) {
	temper.Covers(t, "cli.matrix")
	temper.Covers(t, "matrix.output_deterministic", temper.Subject("cli"))
	a := smallSet()
	b := NewSet()
	b.Put("lattice", "heuristics", "up.working", "", "integration", NotRequired)
	b.Put("lattice", "heuristics", "up.working", "", "unit", Covered)
	b.Put("lattice", "sink.types", "list<int64>", "sink.kafka", "integration", Unenforced)
	b.Put("lattice", "sink.types", "list<int64>", "sink.kafka", "unit", NotRequired)
	b.Put("invariant", "sink.flush.keeps_batch", "", "sink.kafka", "integration", Exempt)
	b.Put("invariant", "sink.flush.keeps_batch", "", "sink.kafka", "unit", NotRequired)
	b.Put("feature", "cli.check", "", "", "integration", Failing)
	b.Put("feature", "cli.check", "", "", "unit", Missing)
	b.Put("feature", "sink.kafka", "", "", "integration", NotRequired)
	b.Put("feature", "sink.kafka", "", "", "unit", Covered)
	for i := 0; i < 20; i++ {
		if !reflect.DeepEqual(Files(a, lv), Files(b, lv)) {
			t.Fatal("the same set built in another order renders different bytes")
		}
	}
}

