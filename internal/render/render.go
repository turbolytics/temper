// Package render writes MATRIX.md from the committed statuses and the
// declarations. It never reads evidence, so the page changes only when a
// status does, and a pull request's diff of MATRIX.md shows exactly the cells
// it moved.
//
// Format 2 is written for engineers auditing a system: what needs attention
// comes first, each invariant is one row with a column per subject, each
// promise sits under its table, and refusals read differently from
// exemptions.
package render

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"github.com/turbolytics/temper/internal/model"
	"github.com/turbolytics/temper/internal/status"
)

// Header opens MATRIX.md.
const Header = "<!-- Generated by temper. Do not edit by hand. -->"

// FormatLine follows the header and names the page's format.
const FormatLine = "<!-- temper matrix format: 2 -->"

// unsupported is how a refused lattice answer reads. Its committed status is
// exempt, and the declarations say why.
const unsupported = "unsupported"

var symbols = map[status.Status]string{
	status.Covered:     "✅",
	status.Exempt:      "☑️",
	status.Failing:     "❌",
	status.Missing:     "⬜",
	status.Unenforced:  "⏳",
	status.NotRequired: "—",
}

const unsupportedSymbol = "⛔"

// Markdown renders the matrix page.
func Markdown(p *model.Project, s status.Set) []byte {
	w := &writer{p: p, s: s, levels: p.Config.LevelNames()}
	w.intro()
	w.attention()
	w.features()
	w.invariants()
	w.lattices()
	w.exemptions()
	return append(bytes.TrimRight(w.b.Bytes(), "\n"), '\n')
}

type writer struct {
	b      bytes.Buffer
	p      *model.Project
	s      status.Set
	levels []string
}

func (w *writer) line(format string, args ...any) {
	fmt.Fprintf(&w.b, format+"\n", args...)
}

// cell escapes text for a table cell and folds it onto one line.
func cell(text string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(text), " "), "|", `\|`)
}

func code(id string) string { return "`" + id + "`" }

func codes(ids []string) []string {
	out := make([]string, len(ids))
	for i, id := range ids {
		out[i] = code(id)
	}
	return out
}

// and joins items as "a", "a and b" or "a, b and c".
func and(items []string) string {
	switch len(items) {
	case 0:
		return ""
	case 1:
		return items[0]
	}
	return strings.Join(items[:len(items)-1], ", ") + " and " + items[len(items)-1]
}

// short drops a subject's kind prefix for a column header in a table that
// holds one kind: cluster.go reads go.
func short(id, kind string) string {
	if rest, ok := strings.CutPrefix(id, kind+"."); ok && rest != "" {
		return rest
	}
	return id
}

// symbol renders one cell. A row the set does not hold reads missing where
// the item requires the level, and not required elsewhere.
func symbol(row status.Row, level string, required map[string]bool) string {
	if st, ok := row[level]; ok {
		return symbols[st]
	}
	if required[level] {
		return symbols[status.Missing]
	}
	return symbols[status.NotRequired]
}

func set(levels []string) map[string]bool {
	out := map[string]bool{}
	for _, l := range levels {
		out[l] = true
	}
	return out
}

// answer is a subject's lattice answer, if it declared one.
func answer(s model.Subject, lattice, member string) (model.Answer, bool) {
	a, ok := s.Answers[lattice][member]
	return a, ok
}

func (w *writer) subject(id string) (model.Subject, bool) {
	for _, s := range w.p.Subjects {
		if s.ID == id {
			return s, true
		}
	}
	return model.Subject{}, false
}

// refused reports whether a lattice cell is a refusal rather than an
// exemption: its subject answered unsupported.
func (w *writer) refused(subjectID, lattice, member string) bool {
	s, ok := w.subject(subjectID)
	if !ok {
		return false
	}
	a, ok := answer(s, lattice, member)
	return ok && !a.Supported
}

func (w *writer) liveFeatures() []model.Feature {
	var out []model.Feature
	for _, f := range w.p.Features {
		if !f.Retired {
			out = append(out, f)
		}
	}
	return out
}

func (w *writer) liveInvariants() []model.Invariant {
	var out []model.Invariant
	for _, inv := range w.p.Invariants {
		if !inv.Retired {
			out = append(out, inv)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

func (w *writer) liveLattices() []model.Lattice {
	var out []model.Lattice
	for _, l := range w.p.Lattices {
		if !l.Retired {
			out = append(out, l)
		}
	}
	return out
}

func (w *writer) liveSubjects() []model.Subject {
	var out []model.Subject
	for _, s := range w.p.Subjects {
		if !s.TestOnly {
			out = append(out, s)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

func plural(n int, one, many string) string {
	if n == 1 {
		return fmt.Sprintf("%d %s", n, one)
	}
	return fmt.Sprintf("%d %s", n, many)
}

func (w *writer) intro() {
	w.line(Header)
	w.line(FormatLine)
	title := w.p.Config.Project
	if title == "" {
		title = "Project"
	}
	w.line("# %s matrix", title)
	w.line("")
	levelWord := "levels"
	if len(w.levels) == 1 {
		levelWord = "level"
	}
	w.line("**%s and %s on %s, at %s %s.**",
		plural(len(w.liveFeatures()), "feature", "features"),
		plural(len(w.liveInvariants()), "invariant", "invariants"),
		plural(len(w.liveSubjects()), "subject", "subjects"),
		levelWord, and(codes(w.levels)))
	w.line("")
	counts := w.counts()
	order := []struct {
		key, sym string
	}{
		{string(status.Covered), symbols[status.Covered]},
		{string(status.Failing), symbols[status.Failing]},
		{string(status.Missing), symbols[status.Missing]},
		{string(status.Exempt), symbols[status.Exempt]},
		{unsupported, unsupportedSymbol},
		{string(status.Unenforced), symbols[status.Unenforced]},
	}
	var parts []string
	for _, o := range order {
		parts = append(parts, fmt.Sprintf("%s %d %s", o.sym, counts[o.key], o.key))
	}
	w.line("%s", strings.Join(parts, " · "))
	w.line("")
	w.line("Each cell is one claim in `%s/` at one level. It is covered when a test that ran", w.p.Config.Dir)
	w.line("at that level passed and none failed: a skip proves nothing, and a pass never hides")
	w.line("a failure. Regenerate with `temper matrix`.")
	w.line("")
	w.line("✅ covered: a test proved it · ❌ failing · ⬜ missing: no passing test ·")
	w.line("☑️ exempt: excused, with proof · ⛔ unsupported: refused, with proof ·")
	w.line("⏳ unenforced: declared, not yet required · — not required")
	w.line("")
}

// counts tallies every cell by how it reads, telling refusals from
// exemptions.
func (w *writer) counts() map[string]int {
	counts := map[string]int{}
	tally := func(row status.Row, refusal bool) {
		for _, st := range row {
			if st == status.NotRequired {
				continue
			}
			if st == status.Exempt && refusal {
				counts[unsupported]++
				continue
			}
			counts[string(st)]++
		}
	}
	for _, row := range w.s.Features {
		tally(row, false)
	}
	for subject, rows := range w.s.Subjects {
		for item, row := range rows {
			refusal := false
			if lattice, member, ok := strings.Cut(item, "/"); ok {
				refusal = w.refused(subject, lattice, member)
			}
			tally(row, refusal)
		}
	}
	for _, rows := range w.s.Lattices {
		for _, row := range rows {
			tally(row, false)
		}
	}
	return counts
}

// attentionRow is a failing, missing or unenforced cell.
type attentionRow struct {
	rank                     int
	kind, item, where, level string
	note                     string
}

func (w *writer) attention() {
	rank := map[status.Status]int{status.Failing: 0, status.Missing: 1, status.Unenforced: 2}
	kindRank := map[string]int{"feature": 0, "invariant": 1, "lattice": 2}
	var rows []attentionRow
	add := func(row status.Row, levels []string, required map[string]bool, kind, item, where, note string) {
		for _, l := range levels {
			st, ok := row[l]
			if !ok {
				if !required[l] {
					continue
				}
				st = status.Missing
			}
			if r, bad := rank[st]; bad {
				rows = append(rows, attentionRow{r, kind, item, where, l, note})
			}
		}
	}
	for _, f := range w.liveFeatures() {
		var req []string
		if f.Requires != nil {
			req = *f.Requires
		}
		add(w.s.Features[f.ID], w.levels, set(req), "feature", f.ID, "", "")
	}
	for _, inv := range w.liveInvariants() {
		levels, _ := inv.RequiredLevels()
		if len(levels) == 0 {
			continue
		}
		note := ""
		if inv.TrackedBy != "" {
			note = "tracked by " + inv.TrackedBy
		}
		for _, subj := range w.p.ApplicableSubjects(inv) {
			add(w.s.Subjects[subj.ID][inv.ID], levels, set(levels), "invariant", inv.ID, subj.ID, note)
		}
	}
	for _, l := range w.liveLattices() {
		for _, m := range l.Members {
			if l.CoveredBy == "scenarios" {
				add(w.s.Lattices[l.ID][m.Key], l.Requires, set(l.Requires), "lattice", l.ID+"/"+m.Key, "", "")
				continue
			}
			for _, subj := range w.liveSubjects() {
				row, ok := w.s.Subjects[subj.ID][l.ID+"/"+m.Key]
				if !ok {
					continue
				}
				note := ""
				if a, ok := answer(subj, l.ID, m.Key); ok && a.TrackedBy != "" {
					note = "tracked by " + a.TrackedBy
				}
				add(row, l.Requires, map[string]bool{}, "lattice", l.ID+"/"+m.Key, subj.ID, note)
			}
		}
	}
	sort.SliceStable(rows, func(i, j int) bool {
		a, b := rows[i], rows[j]
		if a.rank != b.rank {
			return a.rank < b.rank
		}
		if kindRank[a.kind] != kindRank[b.kind] {
			return kindRank[a.kind] < kindRank[b.kind]
		}
		if a.item != b.item {
			return a.item < b.item
		}
		if a.where != b.where {
			return a.where < b.where
		}
		return a.level < b.level
	})

	w.line("## Needs attention")
	w.line("")
	if len(rows) == 0 {
		w.line("Nothing is failing, missing or unenforced.")
		w.line("")
		return
	}
	names := map[int]string{
		0: symbols[status.Failing] + " failing",
		1: symbols[status.Missing] + " missing",
		2: symbols[status.Unenforced] + " unenforced",
	}
	w.line("| Status | Kind | Item | Subject | Level | Note |")
	w.line("| --- | --- | --- | --- | --- | --- |")
	for _, r := range rows {
		where := ""
		if r.where != "" {
			where = code(r.where)
		}
		w.line("| %s | %s | %s | %s | %s | %s |", names[r.rank], r.kind, code(r.item), where, code(r.level), cell(r.note))
	}
	w.line("")
}

func (w *writer) levelHeader(first ...string) {
	cols := append(append([]string{}, first...), codes(w.levels)...)
	w.line("| %s |", strings.Join(cols, " | "))
	seps := make([]string, len(cols))
	for i := range seps {
		seps[i] = "---"
	}
	w.line("| %s |", strings.Join(seps, " | "))
}

func (w *writer) features() {
	w.line("## Features")
	w.line("")
	w.line("What the system does. Each feature is proven at the levels it requires.")
	w.line("")
	w.levelHeader("Feature", "What it does")
	for _, f := range w.liveFeatures() {
		var req []string
		if f.Requires != nil {
			req = *f.Requires
		}
		required := set(req)
		cells := []string{code(f.ID), cell(f.Description)}
		for _, l := range w.levels {
			cells = append(cells, symbol(w.s.Features[f.ID], l, required))
		}
		w.line("| %s |", strings.Join(cells, " | "))
	}
	w.line("")
}

// kindOf is the subject kind an invariant applies to, without capabilities.
func kindOf(appliesTo string) string {
	kind, _, _ := strings.Cut(appliesTo, "+")
	return kind
}

func (w *writer) invariants() {
	invs := w.liveInvariants()
	if len(invs) == 0 {
		return
	}
	byKind := map[string][]model.Invariant{}
	var kinds []string
	for _, inv := range invs {
		k := kindOf(inv.AppliesTo)
		if _, seen := byKind[k]; !seen {
			kinds = append(kinds, k)
		}
		byKind[k] = append(byKind[k], inv)
	}
	sort.Strings(kinds)

	w.line("## Invariants")
	w.line("")
	w.line("What the system must never do, or must always do, for each subject it applies to.")
	w.line("")
	for _, kind := range kinds {
		var subjects []model.Subject
		for _, s := range w.liveSubjects() {
			if s.Kind == kind {
				subjects = append(subjects, s)
			}
		}
		w.line("### %s invariants", code(kind))
		w.line("")
		var table []model.Invariant
		multi := false
		for _, inv := range byKind[kind] {
			if levels, _ := inv.RequiredLevels(); len(levels) > 0 {
				table = append(table, inv)
				multi = multi || len(levels) > 1
			}
		}
		if len(table) > 0 && len(subjects) > 0 {
			if multi {
				w.line("Where a row names several levels, each cell shows one mark per level, in that order.")
				w.line("")
			}
			head := []string{"Invariant", "Family", "Levels"}
			for _, s := range subjects {
				head = append(head, code(short(s.ID, kind)))
			}
			w.line("| %s |", strings.Join(head, " | "))
			seps := make([]string, len(head))
			for i := range seps {
				seps[i] = "---"
			}
			w.line("| %s |", strings.Join(seps, " | "))
			for _, inv := range table {
				levels, anyOne := inv.RequiredLevels()
				required := set(levels)
				applies := map[string]bool{}
				for _, s := range w.p.ApplicableSubjects(inv) {
					applies[s.ID] = true
				}
				family := inv.Family
				if family == "" {
					family = "—"
				}
				levelText := strings.Join(codes(levels), ", ")
				if anyOne {
					levelText = "any of " + levelText
				}
				cells := []string{fmt.Sprintf("[%s](#inv-%s)", code(inv.ID), inv.ID), cell(family), levelText}
				for _, s := range subjects {
					if !applies[s.ID] {
						cells = append(cells, symbols[status.NotRequired])
						continue
					}
					var marks []string
					for _, l := range levels {
						marks = append(marks, symbol(w.s.Subjects[s.ID][inv.ID], l, required))
					}
					cells = append(cells, strings.Join(marks, " "))
				}
				w.line("| %s |", strings.Join(cells, " | "))
			}
			w.line("")
		}
		for _, inv := range byKind[kind] {
			var tags []string
			for _, t := range []string{inv.Class, inv.Family} {
				if t != "" {
					tags = append(tags, t)
				}
			}
			text := fmt.Sprintf(`- <a id="inv-%s"></a>**%s**`, inv.ID, code(inv.ID))
			if len(tags) > 0 {
				text += " · " + strings.Join(tags, " · ")
			}
			text += " — " + cell(inv.Claim)
			switch levels, anyOne := inv.RequiredLevels(); {
			case len(levels) == 0:
				text += " (declared, no levels required)"
			case anyOne:
				text += " Proven at any one of: " + strings.Join(levels, ", ") + "."
			}
			if inv.TrackedBy != "" {
				text += " Tracked by " + inv.TrackedBy + "."
			}
			if len(inv.ViolatedOnce) > 0 {
				text += " Violated once: " + strings.Join(inv.ViolatedOnce, ", ") + "."
			}
			w.line("%s", text)
		}
		w.line("")
	}
}

func (w *writer) lattices() {
	lats := w.liveLattices()
	if len(lats) == 0 {
		return
	}
	w.line("## Lattices")
	w.line("")
	w.line("Complete lists of cases. Every subject a lattice applies to answers for every member.")
	w.line("")
	for _, l := range lats {
		w.line("### %s", code(l.ID))
		w.line("")
		desc := cell(l.Description)
		if l.CoveredBy == "scenarios" {
			desc += " Covered by scenarios."
		}
		w.line("%s", desc)
		w.line("")
		if l.CoveredBy == "scenarios" {
			required := set(l.Requires)
			w.levelHeader("Member")
			for _, m := range l.Members {
				cells := []string{code(m.Key)}
				for _, lv := range w.levels {
					cells = append(cells, symbol(w.s.Lattices[l.ID][m.Key], lv, required))
				}
				w.line("| %s |", strings.Join(cells, " | "))
			}
			w.line("")
			continue
		}
		var subjects []model.Subject
		for _, s := range w.liveSubjects() {
			if w.p.LatticeApplies(l, s) {
				subjects = append(subjects, s)
			}
		}
		if len(l.Requires) > 1 {
			// Subjects take the columns, so each cell holds one mark per level.
			w.line("Each cell shows one mark per level, in order: %s.", strings.Join(codes(l.Requires), ", "))
			w.line("")
		}
		kind := kindOf(l.AppliesTo)
		head := []string{"Member"}
		sep := []string{"---"}
		for _, s := range subjects {
			head = append(head, code(short(s.ID, kind)))
			sep = append(sep, "---")
		}
		w.line("| %s |", strings.Join(head, " | "))
		w.line("| %s |", strings.Join(sep, " | "))
		for _, m := range l.Members {
			cells := []string{code(m.Key)}
			for _, s := range subjects {
				row, ok := w.s.Subjects[s.ID][l.ID+"/"+m.Key]
				if !ok {
					cells = append(cells, symbols[status.NotRequired])
					continue
				}
				refusal := w.refused(s.ID, l.ID, m.Key)
				var marks []string
				for _, lv := range l.Requires {
					st, ok := row[lv]
					if !ok {
						continue
					}
					if st == status.Exempt && refusal {
						marks = append(marks, unsupportedSymbol)
					} else {
						marks = append(marks, symbols[st])
					}
				}
				if len(marks) == 0 {
					marks = []string{symbols[status.NotRequired]}
				}
				cells = append(cells, strings.Join(marks, " "))
			}
			w.line("| %s |", strings.Join(cells, " | "))
		}
		w.line("")
	}
}

// exemptions lists every excused cell with its reason and proof, so a
// reviewer can audit each ☑️ and ⛔.
func (w *writer) exemptions() {
	var lines []string
	for _, s := range w.liveSubjects() {
		for _, e := range s.Exempt {
			text := fmt.Sprintf("- %s × %s: exempt. %s", code(s.ID), code(e.Invariant), cell(e.Reason))
			if e.ProvenBy != "" {
				text += " Proven by " + code(e.ProvenBy) + "."
			}
			lines = append(lines, text)
		}
	}
	for _, l := range w.liveLattices() {
		for _, m := range l.Members {
			for _, s := range w.liveSubjects() {
				a, ok := answer(s, l.ID, m.Key)
				if !ok || a.Supported {
					continue
				}
				text := fmt.Sprintf("- %s × %s: unsupported. %s", code(s.ID), code(l.ID+"/"+m.Key), cell(a.Reason))
				if a.ProvenBy != "" {
					text += " Proven by " + code(a.ProvenBy) + "."
				}
				if a.TrackedBy != "" {
					text += " Tracked by " + a.TrackedBy + "."
				}
				lines = append(lines, text)
			}
		}
	}
	if len(lines) == 0 {
		return
	}
	w.line("## Exemptions and refusals")
	w.line("")
	w.line("Each ☑️ and ⛔, with the reason and the test that proves it.")
	w.line("")
	for _, l := range lines {
		w.line("%s", l)
	}
	w.line("")
}
