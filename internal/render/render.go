// Package render writes MATRIX.md from the committed statuses and the
// declarations. It never reads evidence, so the page changes only when a
// status does.
package render

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"github.com/turbolytics/temper/internal/model"
	"github.com/turbolytics/temper/internal/status"
)

// Header opens MATRIX.md.
const Header = "<!-- Generated by temper. Do not edit by hand. -->"

var symbols = map[status.Status]string{
	status.Covered:     "✅",
	status.Exempt:      "☑️",
	status.Failing:     "❌",
	status.Missing:     "⬜",
	status.Unenforced:  "⏳",
	status.NotRequired: "—",
}

var summaryOrder = []status.Status{status.Covered, status.Exempt, status.Failing, status.Missing, status.Unenforced}

// Markdown renders the matrix page.
func Markdown(p *model.Project, s status.Set) []byte {
	w := &writer{p: p, s: s, levels: p.Config.LevelNames()}
	w.intro()
	w.summary()
	w.features()
	w.invariants()
	w.lattices()
	return append(bytes.TrimRight(w.b.Bytes(), "\n"), '\n')
}

type writer struct {
	b      bytes.Buffer
	p      *model.Project
	s      status.Set
	levels []string
}

func (w *writer) line(format string, args ...any) {
	fmt.Fprintf(&w.b, format+"\n", args...)
}

// cell escapes text for a table cell and folds it onto one line.
func cell(text string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(text), " "), "|", `\|`)
}

func code(id string) string { return "`" + id + "`" }

// symbol renders one cell. A row the set does not hold reads missing where
// the item requires the level, and not required elsewhere.
func symbol(row status.Row, level string, required map[string]bool) string {
	if st, ok := row[level]; ok {
		return symbols[st]
	}
	if required[level] {
		return symbols[status.Missing]
	}
	return symbols[status.NotRequired]
}

func set(levels []string) map[string]bool {
	out := map[string]bool{}
	for _, l := range levels {
		out[l] = true
	}
	return out
}

func (w *writer) levelHeader(first ...string) {
	cols := append(append([]string{}, first...), w.levels...)
	w.line("| %s |", strings.Join(cols, " | "))
	seps := make([]string, len(cols))
	for i := range seps {
		seps[i] = "---"
	}
	w.line("| %s |", strings.Join(seps, " | "))
}

func (w *writer) intro() {
	w.line(Header)
	title := w.p.Config.Project
	if title == "" {
		title = "Project"
	}
	w.line("# %s matrix", title)
	w.line("")
	w.line("Every row is a claim this project declares in `%s/`. A cell is covered when a test", w.p.Config.Dir)
	w.line("that ran at that level passed and none failed. A skip proves nothing, and a pass")
	w.line("never hides a failure.")
	w.line("Exempt cells are excused by a passing proof. Regenerate with `temper matrix`.")
	w.line("")
	w.line("✅ covered · ☑️ exempt · ❌ failing · ⬜ missing · ⏳ unenforced · — not required")
	w.line("")
}

func (w *writer) summary() {
	counts := map[status.Status]int{}
	count := func(rows map[string]status.Row) {
		for _, row := range rows {
			for _, st := range row {
				counts[st]++
			}
		}
	}
	count(w.s.Features)
	for _, rows := range w.s.Subjects {
		count(rows)
	}
	for _, rows := range w.s.Lattices {
		count(rows)
	}
	w.line("## Summary")
	w.line("")
	var head, sep, vals []string
	for _, st := range summaryOrder {
		head = append(head, string(st))
		sep = append(sep, "---:")
		vals = append(vals, fmt.Sprint(counts[st]))
	}
	w.line("| %s |", strings.Join(head, " | "))
	w.line("| %s |", strings.Join(sep, " | "))
	w.line("| %s |", strings.Join(vals, " | "))
	w.line("")
}

func (w *writer) features() {
	w.line("## Features")
	w.line("")
	w.levelHeader("Feature", "What it does")
	for _, f := range w.p.Features {
		if f.Retired {
			continue
		}
		var req []string
		if f.Requires != nil {
			req = *f.Requires
		}
		required := set(req)
		cells := []string{code(f.ID), cell(f.Description)}
		for _, l := range w.levels {
			cells = append(cells, symbol(w.s.Features[f.ID], l, required))
		}
		w.line("| %s |", strings.Join(cells, " | "))
	}
	w.line("")
}

func (w *writer) invariants() {
	families := map[string][]model.Invariant{}
	for _, inv := range w.p.Invariants {
		if inv.Retired {
			continue
		}
		fam := inv.Family
		if fam == "" {
			fam = "Other"
		}
		families[fam] = append(families[fam], inv)
	}
	if len(families) == 0 {
		return
	}
	names := make([]string, 0, len(families))
	for name := range families {
		if name != "Other" {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	if _, ok := families["Other"]; ok {
		names = append(names, "Other")
	}

	w.line("## Invariants")
	w.line("")
	for _, name := range names {
		invs := families[name]
		sort.Slice(invs, func(i, j int) bool { return invs[i].ID < invs[j].ID })
		w.line("### %s", name)
		w.line("")
		var rows []string
		for _, inv := range invs {
			levels, _ := inv.RequiredLevels()
			if len(levels) == 0 {
				continue
			}
			required := set(levels)
			for _, subj := range w.p.ApplicableSubjects(inv) {
				cells := []string{code(inv.ID), code(subj.ID)}
				for _, l := range w.levels {
					cells = append(cells, symbol(w.s.Subjects[subj.ID][inv.ID], l, required))
				}
				rows = append(rows, "| "+strings.Join(cells, " | ")+" |")
			}
		}
		if len(rows) > 0 {
			w.levelHeader("Invariant", "Subject")
			for _, r := range rows {
				w.line("%s", r)
			}
			w.line("")
		}
		for _, inv := range invs {
			text := fmt.Sprintf("- %s — %s", code(inv.ID), cell(inv.Claim))
			switch levels, anyOne := inv.RequiredLevels(); {
			case len(levels) == 0:
				text += " (declared, no levels required)"
			case anyOne:
				text += " Proven at any one of: " + strings.Join(levels, ", ") + "."
			}
			if inv.TrackedBy != "" {
				text += " Tracked by " + inv.TrackedBy + "."
			}
			if len(inv.ViolatedOnce) > 0 {
				text += " Violated once: " + strings.Join(inv.ViolatedOnce, ", ") + "."
			}
			w.line("%s", text)
		}
		w.line("")
	}
}

func (w *writer) lattices() {
	var lats []model.Lattice
	for _, l := range w.p.Lattices {
		if !l.Retired {
			lats = append(lats, l)
		}
	}
	if len(lats) == 0 {
		return
	}
	w.line("## Lattices")
	w.line("")
	for _, l := range lats {
		w.line("### %s", code(l.ID))
		w.line("")
		desc := cell(l.Description)
		if l.CoveredBy == "scenarios" {
			desc += " Covered by scenarios."
		}
		w.line("%s", desc)
		w.line("")
		if l.CoveredBy == "scenarios" {
			required := set(l.Requires)
			w.levelHeader("Member")
			for _, m := range l.Members {
				cells := []string{code(m.Key)}
				for _, lv := range w.levels {
					cells = append(cells, symbol(w.s.Lattices[l.ID][m.Key], lv, required))
				}
				w.line("| %s |", strings.Join(cells, " | "))
			}
			w.line("")
			continue
		}
		var subjects []model.Subject
		for _, s := range w.p.Subjects {
			if !s.TestOnly && w.p.LatticeApplies(l, s) {
				subjects = append(subjects, s)
			}
		}
		sort.Slice(subjects, func(i, j int) bool { return subjects[i].ID < subjects[j].ID })
		head := []string{"Member"}
		sep := []string{"---"}
		for _, s := range subjects {
			head = append(head, code(s.ID))
			sep = append(sep, "---")
		}
		w.line("| %s |", strings.Join(head, " | "))
		w.line("| %s |", strings.Join(sep, " | "))
		for _, m := range l.Members {
			cells := []string{code(m.Key)}
			for _, s := range subjects {
				row, ok := w.s.Subjects[s.ID][l.ID+"/"+m.Key]
				if !ok {
					cells = append(cells, symbols[status.NotRequired])
					continue
				}
				var marks []string
				for _, lv := range l.Requires {
					if st, ok := row[lv]; ok {
						marks = append(marks, symbols[st])
					}
				}
				if len(marks) == 0 {
					marks = []string{symbols[status.NotRequired]}
				}
				cells = append(cells, strings.Join(marks, " "))
			}
			w.line("| %s |", strings.Join(cells, " | "))
		}
		w.line("")
	}
}
